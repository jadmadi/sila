// Helper formatting functions for CLI help output
func printSkillHelpLine(o io.Writer, ui render.UI, left, right string) {
	if len(left) < 24 {
		pad := strings.Repeat(" ", 24-len(left))
		fmt.Fprintf(o, "  %s%s %s\n", ui.Bold(left), pad, right)
	} else {
		fmt.Fprintf(o, "  %s\n  %24s %s\n", ui.Bold(left), "", right)
	}
}

