var subcommandUsageOut io.Writer = os.Stderr

func subcommandUsage(sub string, ui render.UI) {
	subcommandUsageTo(sub, ui, os.Stderr)
}

// subcommandUsageTo centralizes the help stream: explicit --help passes
// os.Stdout, while error usage keeps os.Stderr.
func subcommandUsageTo(sub string, ui render.UI, out io.Writer) {
	previous := subcommandUsageOut
	subcommandUsageOut = out
	defer func() { subcommandUsageOut = previous }()
	if sub == "phrases" {
		runCCLIHelpPhrases(out)
		return
	}
	if subcommandUsageCore(sub, ui) {
		appendSubcommandCCLIHelp(sub, ui, out)
		return
	}
	if subcommandUsageOps(sub, ui) {
		appendSubcommandCCLIHelp(sub, ui, out)
		return
	}
	if subcommandUsageRegistry(sub, ui, out) {
		appendSubcommandCCLIHelp(sub, ui, out)
		return
	}
	usageTo(subcommandUsageOut)
}

