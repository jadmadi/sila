package dream

import (
	"fmt"
	"strings"
	"time"

	"github.com/jadmadi/sila/internal/store"
)

// CompileRules builds a unified rules/instructions document for specific AI coding agents.
func CompileRules(st *store.Store, projectID, target string) (string, error) {
	if projectID == "" {
		projectID = "global"
	}
	target = strings.ToLower(strings.TrimSpace(target))
	if target == "" {
		target = "claude"
	}

	facts, err := st.FactsByProject(projectID)
	if err != nil {
		facts = nil
	}

	handoff, _ := st.LatestHandoff(projectID)
	docs, _ := st.DocsByProject(projectID, 20)

	var verifiedMemos []store.Fact
	var verifiedDirectives []store.Fact
	var distilledFacts []store.Fact
	var fileClaims []store.Fact
	for _, f := range facts {
		if f.SessionRef == "manual_memo" {
			// Explicit memos are the authorized write path: always authoritative.
			verifiedMemos = append(verifiedMemos, f)
		} else if f.IsCandidate() {
			// Inferred candidates are never exported as hard constraints;
			// authority requires an explicit human decision.
			continue
		} else if f.Kind == "invariant" || strings.EqualFold(f.Confidence, "invariant") {
			verifiedDirectives = append(verifiedDirectives, f)
		} else if f.IsFact() {
			// Corroborated, distilled, and file-grounded: a real fact.
			distilledFacts = append(distilledFacts, f)
		} else if f.FileRefsExist || f.Verified {
			// Quotes a real file but was never corroborated or distilled. It is
			// a claim, and exporting it under a "Facts" heading would put raw
			// session text into a rule file agents treat as a hard constraint.
			fileClaims = append(fileClaims, f)
		}
	}

	allDirectives := append([]store.Fact{}, verifiedMemos...)
	allDirectives = append(allDirectives, verifiedDirectives...)

	var b strings.Builder
	now := time.Now().UTC().Format("2006-01-02 15:04")

	switch target {
	case "cursor", ".cursorrules":
		b.WriteString(fmt.Sprintf("# Cursor Project Rules — %s\n# Auto-generated by sila on %s\n\n", projectID, now))

		if len(allDirectives) > 0 {
			b.WriteString("## Critical Architectural Directives & Invariants\n")
			seenClaims := make(map[string]bool)
			for _, m := range allDirectives {
				c := strings.TrimSpace(m.Claim)
				if !seenClaims[strings.ToLower(c)] {
					seenClaims[strings.ToLower(c)] = true
					b.WriteString(fmt.Sprintf("- %s\n", c))
				}
			}
			b.WriteString("\n")
		}

		if handoff != nil {
			b.WriteString("## Current State & Active Tasks\n")
			b.WriteString(fmt.Sprintf("- Active Goal: %s\n", handoff.Summary))
			for _, item := range handoff.OpenItems {
				b.WriteString(fmt.Sprintf("- Task: %s\n", item))
			}
			b.WriteString("\n")
		}

		if len(distilledFacts) > 0 {
			b.WriteString("## Codebase Facts & Verified Files\n")
			for _, f := range distilledFacts {
				desc := f.Distilled
				if desc == "" {
					desc = f.Claim
				}
				filesPart := ""
				if len(f.RepoFiles) > 0 {
					filesPart = fmt.Sprintf(" (files: %s)", strings.Join(f.RepoFiles, ", "))
				}
				b.WriteString(fmt.Sprintf("- %s%s\n", desc, filesPart))
			}
			b.WriteString("\n")
		}

		if len(fileClaims) > 0 {
			b.WriteString("## File-Referenced Claims (observed in sessions, not distilled — verify before treating as rules)\n")
			for _, f := range fileClaims {
				desc := f.Distilled
				if desc == "" {
					desc = f.Claim
				}
				filesPart := ""
				if len(f.RepoFiles) > 0 {
					filesPart = fmt.Sprintf(" (files: %s)", strings.Join(f.RepoFiles, ", "))
				}
				b.WriteString(fmt.Sprintf("- %s%s\n", desc, filesPart))
			}
			b.WriteString("\n")
		}

		if len(docs) > 0 {
			b.WriteString("## Attached Reference Documentation\n")
			for _, d := range docs {
				b.WriteString(fmt.Sprintf("- %s (%s)\n", d.Title, d.URL))
			}
			b.WriteString("\n")
		}

	case "windsurf", ".windsurfrules":
		b.WriteString(fmt.Sprintf("# Windsurf Project Rules — %s\n# Auto-generated by sila on %s\n\n", projectID, now))
		if len(allDirectives) > 0 {
			b.WriteString("### Architectural Constraints & Directives\n")
			seenClaims := make(map[string]bool)
			for _, m := range allDirectives {
				c := strings.TrimSpace(m.Claim)
				if !seenClaims[strings.ToLower(c)] {
					seenClaims[strings.ToLower(c)] = true
					b.WriteString(fmt.Sprintf("* %s\n", c))
				}
			}
			b.WriteString("\n")
		}
		if handoff != nil {
			b.WriteString("### Active Handoff\n")
			b.WriteString(fmt.Sprintf("* **Summary**: %s\n", handoff.Summary))
			for _, item := range handoff.OpenItems {
				b.WriteString(fmt.Sprintf("* **Task**: %s\n", item))
			}
			b.WriteString("\n")
		}
		if len(distilledFacts) > 0 {
			b.WriteString("### Verified Facts\n")
			for _, f := range distilledFacts {
				desc := f.Distilled
				if desc == "" {
					desc = f.Claim
				}
				b.WriteString(fmt.Sprintf("* %s\n", desc))
			}
			b.WriteString("\n")
		}

		if len(fileClaims) > 0 {
			b.WriteString("### File-Referenced Claims (observed in sessions, not distilled — verify before treating as rules)\n")
			for _, f := range fileClaims {
				desc := f.Distilled
				if desc == "" {
					desc = f.Claim
				}
				b.WriteString(fmt.Sprintf("* %s\n", desc))
			}
			b.WriteString("\n")
		}

	default: // claude (CLAUDE.md) or agents (AGENTS.md)
		docName := "CLAUDE.md"
		if target == "agents" || target == "agents.md" {
			docName = "AGENTS.md"
		}
		b.WriteString(fmt.Sprintf("# %s — %s\n\n", docName, projectID))
		b.WriteString(fmt.Sprintf("> Auto-compiled by `sila` on %s. Codebase is source of truth.\n\n", now))

		if len(allDirectives) > 0 {
			b.WriteString("## Hard Architectural Constraints & Directives\n\n")
			seenClaims := make(map[string]bool)
			for _, m := range allDirectives {
				c := strings.TrimSpace(m.Claim)
				if !seenClaims[strings.ToLower(c)] {
					seenClaims[strings.ToLower(c)] = true
					b.WriteString(fmt.Sprintf("- **%s**\n", c))
				}
			}
			b.WriteString("\n")
		}

		if handoff != nil {
			b.WriteString("## Active Session Handoff\n\n")
			b.WriteString(fmt.Sprintf("- **Summary**: %s\n", handoff.Summary))
			if len(handoff.OpenItems) > 0 {
				b.WriteString("- **Open Tasks**:\n")
				for _, item := range handoff.OpenItems {
					b.WriteString(fmt.Sprintf("  - [ ] %s\n", strings.TrimPrefix(item, "- [ ] ")))
				}
			}
			if len(handoff.Decisions) > 0 {
				b.WriteString("- **Recent Decisions**:\n")
				for _, d := range handoff.Decisions {
					b.WriteString(fmt.Sprintf("  - %s\n", d))
				}
			}
			b.WriteString("\n")
		}

		if len(distilledFacts) > 0 {
			b.WriteString("## Grounded Codebase Facts\n\n")
			for _, f := range distilledFacts {
				desc := f.Distilled
				if desc == "" {
					desc = f.Claim
				}
				tools := strings.Join(f.Tools, ", ")
				filesPart := ""
				if len(f.RepoFiles) > 0 {
					filesPart = fmt.Sprintf(" (`%s`)", strings.Join(f.RepoFiles, ", "))
				}
				b.WriteString(fmt.Sprintf("- %s%s _[%s]_\n", desc, filesPart, tools))
			}
			b.WriteString("\n")
		}

		if len(fileClaims) > 0 {
			b.WriteString("## File-Referenced Claims (observed in sessions, not distilled — verify before treating as rules)\n\n")
			for _, f := range fileClaims {
				desc := f.Distilled
				if desc == "" {
					desc = f.Claim
				}
				tools := strings.Join(f.Tools, ", ")
				filesPart := ""
				if len(f.RepoFiles) > 0 {
					filesPart = fmt.Sprintf(" (`%s`)", strings.Join(f.RepoFiles, ", "))
				}
				b.WriteString(fmt.Sprintf("- %s%s _[%s]_\n", desc, filesPart, tools))
			}
			b.WriteString("\n")
		}

		if len(docs) > 0 {
			b.WriteString("## Attached Reference Documentation\n\n")
			for _, d := range docs {
				urlPart := ""
				if d.URL != "" {
					urlPart = fmt.Sprintf(" (%s)", d.URL)
				}
				b.WriteString(fmt.Sprintf("- **%s**%s\n", d.Title, urlPart))
			}
			b.WriteString("\n")
		}
	}

	return b.String(), nil
}
