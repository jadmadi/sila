package gate

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// SRP Thresholds
const (
	// SoftCeilingLines triggers an architectural advisory warning.
	SoftCeilingLines = 1000
	// SoftCeilingTokens triggers an architectural advisory warning based on estimated token weight.
	SoftCeilingTokens = 10000
	// HardCeilingNewFileLines blocks brand-new monolithic files added in a single commit.
	HardCeilingNewFileLines = 2000
)

// StagedFile represents a file inspected from the git staging area.
type StagedFile struct {
	Path   string `json:"path"`   // Relative path to repository root
	Status string `json:"status"` // "A" (added), "M" (modified), "R" (renamed), "D" (deleted), etc.
}

// SRPIssue represents an advisory warning or blocking rejection generated by the SRP sentry.
type SRPIssue struct {
	Path      string `json:"path"`
	Status    string `json:"status"`
	Lines     int    `json:"lines"`
	Tokens    int    `json:"tokens"`
	IsNewFile bool   `json:"is_new_file"`
	Severity  string `json:"severity"` // "warn" | "reject"
	Message   string `json:"message"`
}

// SRPResult summarizes the Single Responsibility sentry evaluation.
type SRPResult struct {
	Passed   bool       `json:"passed"`
	Issues   []SRPIssue `json:"issues"`
	Scanned  int        `json:"scanned"`
	Excluded int        `json:"excluded"`
}

// IsSRPExcluded returns true if the given file path should be ignored by SRP weight sentry.
// Ignores vendored code, generated files, test fixtures, minified assets, and non-source files.
func IsSRPExcluded(path string, content []byte) bool {
	norm := filepath.ToSlash(path)

	// Vendor directories
	if strings.HasPrefix(norm, "vendor/") || strings.Contains(norm, "/vendor/") ||
		strings.HasPrefix(norm, "node_modules/") || strings.Contains(norm, "/node_modules/") ||
		strings.HasPrefix(norm, "third_party/") || strings.Contains(norm, "/third_party/") {
		return true
	}

	// Test fixtures & testdata
	if strings.Contains(norm, "/testdata/") || strings.HasPrefix(norm, "testdata/") ||
		strings.Contains(norm, "/fixtures/") || strings.HasPrefix(norm, "fixtures/") {
		return true
	}

	// Generated code files
	base := filepath.Base(norm)
	if strings.HasSuffix(base, "_gen.go") || base == "schema.ts" || strings.HasSuffix(base, ".pb.go") ||
		strings.HasSuffix(base, "_generated.go") || strings.HasSuffix(base, ".gen.ts") || strings.HasSuffix(base, ".gen.go") {
		return true
	}

	// Minified bundles
	if strings.HasSuffix(base, ".min.js") || strings.HasSuffix(base, ".min.css") ||
		strings.HasSuffix(base, ".bundle.js") || strings.HasSuffix(base, ".min.map") {
		return true
	}

	// Lock files and data / config files
	if base == "go.sum" || base == "package-lock.json" || base == "pnpm-lock.yaml" ||
		base == "yarn.lock" || base == "Cargo.lock" || strings.HasSuffix(base, ".lock") {
		return true
	}

	// Check if this is a recognized source file extension
	ext := strings.ToLower(filepath.Ext(base))
	sourceExts := map[string]bool{
		".go":   true,
		".ts":   true,
		".tsx":  true,
		".js":   true,
		".jsx":  true,
		".py":   true,
		".rs":   true,
		".c":    true,
		".cpp":  true,
		".cc":   true,
		".h":    true,
		".hpp":  true,
		".java": true,
		".sh":   true,
		".bash": true,
		".rb":   true,
		".php":  true,
	}
	if !sourceExts[ext] {
		return true
	}

	// Check header for generated file markers
	if len(content) > 0 {
		headerLen := 512
		if len(content) < headerLen {
			headerLen = len(content)
		}
		header := string(content[:headerLen])
		if strings.Contains(header, "Code generated") && strings.Contains(header, "DO NOT EDIT") {
			return true
		}
		if strings.Contains(header, "GENERATED BY") || strings.Contains(header, "@generated") {
			return true
		}
	}

	return false
}

// EstimateTokens provides a deterministic token weight approximation (~4 characters per token).
func EstimateTokens(content []byte) int {
	if len(content) == 0 {
		return 0
	}
	tokens := len(content) / 4
	if tokens == 0 {
		return 1
	}
	return tokens
}

// CountLines counts the total lines of code in file content.
func CountLines(content []byte) int {
	if len(content) == 0 {
		return 0
	}
	n := bytes.Count(content, []byte("\n"))
	if len(content) > 0 && content[len(content)-1] != '\n' {
		n++
	}
	return n
}

// CheckSRP evaluates staged files against Single Responsibility file weight and token thresholds.
// repoRoot is the base directory of the repository (or current working directory).
func CheckSRP(repoRoot string, staged []StagedFile) SRPResult {
	res := SRPResult{
		Passed: true,
		Issues: make([]SRPIssue, 0),
	}

	for _, sf := range staged {
		// Ignore deletions
		if sf.Status == "D" {
			continue
		}

		filePath := filepath.Join(repoRoot, sf.Path)
		content, err := os.ReadFile(filePath)
		if err != nil {
			// File might not exist on disk (e.g. deleted or outside worktree)
			continue
		}

		if IsSRPExcluded(sf.Path, content) {
			res.Excluded++
			continue
		}

		res.Scanned++
		lines := CountLines(content)
		tokens := EstimateTokens(content)
		isNew := (sf.Status == "A")

		// Hard ceiling check: brand-new monolithic file > 2,000 LOC
		if isNew && lines > HardCeilingNewFileLines {
			res.Passed = false
			res.Issues = append(res.Issues, SRPIssue{
				Path:      sf.Path,
				Status:    sf.Status,
				Lines:     lines,
				Tokens:    tokens,
				IsNewFile: true,
				Severity:  "reject",
				Message: fmt.Sprintf(
					"Brand-new monolithic source file %s exceeds 2,000 LOC (%d lines, ~%d tokens). Blocked by pragmatic SOLID/SRP ceiling; decompose into cohesive sub-packages or helper modules.",
					sf.Path, lines, tokens,
				),
			})
			continue
		}

		// Soft ceiling check: file > 1,000 LOC or ~10,000 tokens
		if lines > SoftCeilingLines || tokens > SoftCeilingTokens {
			res.Issues = append(res.Issues, SRPIssue{
				Path:      sf.Path,
				Status:    sf.Status,
				Lines:     lines,
				Tokens:    tokens,
				IsNewFile: isNew,
				Severity:  "warn",
				Message: fmt.Sprintf(
					"Source file %s exceeds 1,000 LOC or ~10,000 tokens (%d lines, ~%d tokens). Recommending modular package decomposition to prevent cognitive overload.",
					sf.Path, lines, tokens,
				),
			})
		}
	}

	return res
}
