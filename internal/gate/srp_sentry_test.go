func TestCheckSRP_BrandNewMonolithicFileRejected(t *testing.T) {
	tmpDir := t.TempDir()
	bigFilePath := filepath.Join(tmpDir, "monolith.go")

	// Generate 2,500 lines of Go code
	var sb strings.Builder
	sb.WriteString("package monolith\n\n")
	for i := 0; i < 2500; i++ {
		sb.WriteString("// line of code\n")
	}
	if err := os.WriteFile(bigFilePath, []byte(sb.String()), 0644); err != nil {
		t.Fatal(err)
	}

	staged := []StagedFile{
		{Path: "monolith.go", Status: "A"},
	}

	res := CheckSRP(tmpDir, staged)
	if res.Passed {
		t.Fatal("expected brand-new 2500-line file to be rejected by hard ceiling")
	}
	if len(res.Issues) != 1 {
		t.Fatalf("expected 1 issue, got %d", len(res.Issues))
	}
	issue := res.Issues[0]
	if issue.Severity != "reject" {
		t.Errorf("expected severity 'reject', got %q", issue.Severity)
	}
	if !strings.Contains(issue.Message, "exceeds 2,000 LOC") {
		t.Errorf("unexpected message: %s", issue.Message)
	}
}

