package version

import (
	"fmt"
	"regexp"
	"runtime/debug"
	"strconv"
	"strings"
)

// Version, Commit, and Date are set at build time via ldflags:
//
//	go build -ldflags "-X github.com/jadmadi/sila/internal/version.Version=v0.1.0"
//
// build.sh (and future goreleaser) injects them. When building from source
// without ldflags, Version defaults to "dev" and Commit/Date are inferred from runtime/debug.
var (
	Version = "dev"
	Commit  = "unknown"
	Date    = "unknown"
)

var (
	releaseRE = regexp.MustCompile(`^v[0-9]+\.[0-9]+\.[0-9]+(?:-[0-9A-Za-z.-]+)?$`)
	// pseudoRE matches a Go pseudo-version such as
	// v0.0.0-20260101120000-abcdef123456: it identifies a source build, not a
	// published release, so it must never be treated as one.
	pseudoRE = regexp.MustCompile(`^v[0-9]+\.[0-9]+\.[0-9]+-.*[0-9]{14}-[0-9a-f]{7,}$`)
	preRelRE = regexp.MustCompile(`^v[0-9]+\.[0-9]+\.[0-9]+-[0-9A-Za-z.-]+$`)
)

// IsRelease reports whether v is a SemVer release tag accepted by Sila. A Go
// pseudo-version is explicitly not a release: `go install` derives one from
// module metadata, and treating it as a release would invent a version.
func IsRelease(v string) bool { return releaseRE.MatchString(v) && !IsPseudoVersion(v) }

// IsPseudoVersion reports whether v was generated by the Go toolchain from
// module metadata rather than published as a tag.
func IsPseudoVersion(v string) bool { return pseudoRE.MatchString(v) }

// IsPrerelease reports whether v is a SemVer prerelease (for example
// v0.6.0-rc.1), which is a real release identity but not a stable one.
func IsPrerelease(v string) bool { return preRelRE.MatchString(v) && !IsPseudoVersion(v) }

func init() {
	if info, ok := debug.ReadBuildInfo(); ok {
		if Version == "dev" && info.Main.Version != "" && info.Main.Version != "(devel)" {
			Version = info.Main.Version
		}
		var rev, timeStr, modified string
		for _, setting := range info.Settings {
			switch setting.Key {
			case "vcs.revision":
				rev = setting.Value
			case "vcs.time":
				timeStr = setting.Value
			case "vcs.modified":
				if setting.Value == "true" {
					modified = "-dirty"
				}
			}
		}
		if Commit == "unknown" && rev != "" {
			if len(rev) > 7 {
				Commit = rev[:7] + modified
			} else {
				Commit = rev + modified
			}
		}
		if Date == "unknown" && timeStr != "" {
			Date = timeStr
		}
	}
}

// String returns a human-readable version string.
func String() string {
	if IsRelease(Version) {
		kind := ""
		if IsPrerelease(Version) {
			kind = "prerelease, "
		}
		if Commit != "unknown" {
			return fmt.Sprintf("%s (%s%s, %s)", Version, kind, Commit, Date)
		}
		return Version
	}
	if Version != "dev" && Version != "" {
		return fmt.Sprintf("dev (%s, %s, %s)", Version, Commit, Date)
	}
	if Commit != "unknown" {
		return fmt.Sprintf("dev (commit %s, %s)", Commit, Date)
	}
	return "dev (built from source)"
}

// SemverCompare compares two semver strings (vX.Y.Z or X.Y.Z, optionally with -prerelease or +build).
// Returns 1 if v1 > v2, -1 if v1 < v2, 0 if equal.
// "dev" is treated as less than any released version, but equal to "dev".
func SemverCompare(v1, v2 string) int {
	v1 = strings.TrimPrefix(v1, "v")
	v2 = strings.TrimPrefix(v2, "v")
	if v1 == v2 {
		return 0
	}
	if v1 == "dev" || strings.HasPrefix(v1, "dev+") || v1 == "" {
		if v2 == "dev" || strings.HasPrefix(v2, "dev+") || v2 == "" {
			return 0
		}
		return -1
	}
	if v2 == "dev" || strings.HasPrefix(v2, "dev+") || v2 == "" {
		return 1
	}

	cleanV1 := cleanSemver(v1)
	cleanV2 := cleanSemver(v2)

	p1 := strings.Split(cleanV1, ".")
	p2 := strings.Split(cleanV2, ".")

	for i := 0; i < 3; i++ {
		var n1, n2 int
		if i < len(p1) {
			n1, _ = strconv.Atoi(p1[i])
		}
		if i < len(p2) {
			n2, _ = strconv.Atoi(p2[i])
		}
		if n1 > n2 {
			return 1
		}
		if n1 < n2 {
			return -1
		}
	}
	return 0
}

func cleanSemver(v string) string {
	if idx := strings.IndexAny(v, "+-"); idx != -1 {
		v = v[:idx]
	}
	return v
}

// IsBreakingUpgrade reports whether upgrading from current to latest crosses a major
// boundary (in 1.x+) or a minor boundary (in 0.x.y), indicating potential breaking changes.
func IsBreakingUpgrade(current, latest string) bool {
	current = strings.TrimPrefix(current, "v")
	latest = strings.TrimPrefix(latest, "v")
	if current == "dev" || strings.HasPrefix(current, "dev+") || current == "" {
		return false
	}
	if current == latest {
		return false
	}
	cClean := cleanSemver(current)
	lClean := cleanSemver(latest)

	curParts := strings.Split(cClean, ".")
	latParts := strings.Split(lClean, ".")
	if len(curParts) < 2 || len(latParts) < 2 {
		return false
	}
	curMajor, err1 := strconv.Atoi(curParts[0])
	curMinor, err2 := strconv.Atoi(curParts[1])
	latMajor, err3 := strconv.Atoi(latParts[0])
	latMinor, err4 := strconv.Atoi(latParts[1])
	if err1 != nil || err2 != nil || err3 != nil || err4 != nil {
		return false
	}
	if curMajor == 0 || latMajor == 0 {
		return curMajor != latMajor || curMinor != latMinor
	}
	return curMajor != latMajor
}
